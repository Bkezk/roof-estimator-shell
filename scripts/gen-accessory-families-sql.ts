/**
 * Prints the accessory-families migration from the seed module (owner, Oct 26–27):
 *   bun scripts/gen-accessory-families-sql.ts > supabase/migrations/<stamp>_accessory_families.sql
 *
 * Every statement is idempotent (a re-run adds nothing twice): screens insert `where not exists`,
 * rows append only when no row of that screen carries the same Description, adhesive products by
 * name, pitch pans by description, labor rows by Description, item numbers `on conflict do nothing`.
 * The CDR renumber rewrites the old part numbers to the sheet's and is a no-op once done.
 */
import {
  ADHESIVE_PRODUCTS,
  CDR_RENUMBER,
  CUSTOM_APPLICATION_ROWS,
  DURO_LAST_ADDITIONS,
  FAMILY_SCREENS,
  LABOR_ROWS,
  PITCH_PAN_ROWS,
  seedItemNumbers,
  type SeedRow,
} from "../src/lib/pricing-seed/accessory-families";

/** The existing Duro-Last screens' columns (live catalog, verified 2026-10-27). */
const EXISTING_COLUMNS: Record<string, string[]> = {
  "duro_last:sealants": ["Description", "Part #", "Price"],
  "duro_last:pipe_stacks": [
    "Description",
    "Size",
    "Open Part #",
    "Closed Part #",
    "Price",
    "Tan Price",
    "Gray Price",
    "Dark Gray",
    "Terra Cotta",
    "Rock Ply",
  ],
  "duro_last:corners": [
    "Description",
    "Part #",
    "White",
    "Tan",
    "Gray",
    "Dark Gray",
    "Terra Cotta",
  ],
  "duro_last:walk_pads_wall_vents": ["Description", "Part #", "Price"],
  "duro_last:drain_boots": ["Description", "Part #", "Price", "+ for Color"],
  "duro_last:drain_boot_accessories": ["Description", "Part #", "Price"],
  "duro_last:vents": ["Description", "Part #", "Price"],
  "duro_last:fasteners_and_bits": [
    "Part #",
    "Subtype",
    "Description",
    "Price/Box",
    "Fasteners/Box",
  ],
};

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const j = (v: unknown) =>
  `${q(
    JSON.stringify(v)
      .replace(/\},\{/g, "},\n{")
      .replace(/"rows":\[\{/, '"rows":[\n{'),
  )}::jsonb`;

const out: string[] = [];
const emit = (s: string) => out.push(s);

emit(`-- Accessory families (owner, Oct 26–27): generated by scripts/gen-accessory-families-sql.ts
-- from src/lib/pricing-seed/accessory-families.ts — edit the seed, regenerate, never hand-edit.
-- Duro-Tech TPO rows on the Duro-Last screens, the Non-DL TPO (non_dl_tpo) and EPDM (epdm)
-- accessory branches, Duro-Last › Other Accessories, the CDR renumber, the Firestone and
-- TECH-Bond adhesives, the penetration pockets on EXCEPTIONAL Metals › Pitch Pans, the coatings /
-- pavers / garden roof / vapor barrier on Preset Custom Applications, the labor rows and every
-- item number. Idempotent: re-running adds nothing twice.
`);

// 1. New screens.
emit(`-- 1. New catalog screens`);
for (const s of FAMILY_SCREENS) {
  const data = { columns: s.columns, rows: s.rows, help: s.help, extras: {} };
  emit(
    `insert into public.pricing_catalog (id, branch, category, data, sort)
select ${q(s.id)}, ${q(s.branch)}, ${q(s.category)}, ${j(data)}, ${s.sort}
where not exists (select 1 from public.pricing_catalog where id = ${q(s.id)});`,
  );
}

// 2. Rows appended to existing Duro-Last screens (by Description).
const appendRows = (id: string, rows: SeedRow[], rowsKey: string[] = ["rows"]) => {
  const path = `{${rowsKey.join(",")}}`;
  emit(
    `update public.pricing_catalog set data = jsonb_set(data, '${path}',
  coalesce(data#>'${path}', '[]'::jsonb) || coalesce((
    select jsonb_agg(r) from jsonb_array_elements(${j(rows)}) r
    where not exists (
      select 1 from jsonb_array_elements(coalesce(data#>'${path}', '[]'::jsonb)) e
      where e->>'Description' = r->>'Description' or e->>'description' = r->>'description')), '[]'::jsonb))
where id = ${q(id)};`,
  );
};
emit(`\n-- 2. Duro-Tech TPO rows on the Duro-Last screens`);
for (const a of DURO_LAST_ADDITIONS) appendRows(a.screen_id, a.rows);

// 3. CDR renumber.
emit(`\n-- 3. Composite Drain Rings renumbered to the 09/28/2026 sheet (owner, Oct 27 q8)`);
for (const { from, to } of CDR_RENUMBER) {
  emit(
    `update public.pricing_catalog set data = jsonb_set(data, '{rows}', (
  select jsonb_agg(case when r->>'Part #' = ${q(from)} then jsonb_set(r, '{Part #}', to_jsonb(${q(to)}::text)) else r end)
  from jsonb_array_elements(data->'rows') r))
where id = 'duro_last:cdr_rings' and exists (
  select 1 from jsonb_array_elements(data->'rows') r where r->>'Part #' = ${q(from)});`,
  );
  emit(
    `update public.catalog_item_numbers set item_no = ${q(to)} where screen_id = 'duro_last:cdr_rings' and item_no = ${q(from)};`,
  );
}

// 4. Adhesive products.
emit(
  `\n-- 4. Adhesives (Duro-Last › Adhesives master-detail): Firestone, TECH-Bond and I.S.O. products`,
);
for (const p of ADHESIVE_PRODUCTS) {
  const product = {
    name: p.name,
    price: p.price,
    part_no: p.part_no,
    unit_type: p.unit,
    coverage: p.coverage,
  };
  emit(
    `update public.pricing_catalog set data = jsonb_set(data, '{products}', coalesce(data->'products', '[]'::jsonb) || ${j([product])})
where id = 'duro_last:adhesives' and not exists (
  select 1 from jsonb_array_elements(coalesce(data->'products', '[]'::jsonb)) e where e->>'name' = ${q(p.name)});`,
  );
}

// 5. Pitch pans.
emit(`\n-- 5. EXCEPTIONAL Metals › Pitch Pans: Firestone penetration pockets`);
appendRows("duro_last:exceptional_metals", PITCH_PAN_ROWS as unknown as SeedRow[], [
  "subscreens",
  "pitch_pans",
  "rows",
]);

// 6. Preset Custom Applications.
emit(`\n-- 6. Non Duro-Last › Preset Custom Applications`);
appendRows(
  "non_dl:preset_custom_applications",
  CUSTOM_APPLICATION_ROWS.map(({ part: _part, ...r }) => r),
);

// 7. Labor rows.
emit(
  `\n-- 7. Accessory labor rows for the family descriptions (hours copied from the nearest Duro-Last row)`,
);
for (const t of LABOR_ROWS) {
  const rows = t.rows.map(([Description, hours]) => ({ Description, [t.column]: hours }));
  emit(
    `update public.accessory_labor set data = jsonb_set(data, '{rows}',
  coalesce(data->'rows', '[]'::jsonb) || coalesce((
    select jsonb_agg(r) from jsonb_array_elements(${j(rows)}) r
    where not exists (select 1 from jsonb_array_elements(coalesce(data->'rows', '[]'::jsonb)) e where e->>'Description' = r->>'Description')), '[]'::jsonb))
where id = ${q(t.table)};`,
  );
}

// 8. Item numbers: the Part # mappings are derived IN SQL from the rows just loaded (one
// rule per column layout); the few mappings without a Part # column are listed. The seed's
// seedItemNumbers() is the oracle the lead verifies the live table against afterwards.
emit(`\n-- 8. Item numbers`);
const priceColOf = (columns: string[]): string => {
  if (columns.includes("Price")) return "Price";
  if (columns.includes("Price/Box")) return "Price/Box";
  if (columns.includes("Price/Package")) return "Price/Package";
  if (columns.includes("White")) return "White";
  throw new Error(`no price column in ${columns.join(",")}`);
};
const screenCols: Array<[string, string, boolean]> = [
  ...FAMILY_SCREENS.map((s) => [s.id, priceColOf(s.columns), false] as [string, string, boolean]),
  ...DURO_LAST_ADDITIONS.map(
    (a) =>
      [a.screen_id, priceColOf(EXISTING_COLUMNS[a.screen_id]!), true] as [string, string, boolean],
  ),
];
const seededRow = (duroTechOnly: boolean) =>
  duroTechOnly
    ? `(r->>'Description' like 'Duro-Tech TPO %' or r->>'Description' like 'Drain Guard Clamping Ring%')`
    : `true`;
emit(`-- 8a. Part # → the screen's price column`);
for (const [id, col, dt] of screenCols) {
  if (id.endsWith(":pipe_stacks")) continue;
  emit(
    `insert into public.catalog_item_numbers (item_no, screen_id, row_label, price_col, dl_description)
select r->>'Part #', c.id, r->>'Description', ${q(col)}, r->>'Description'
from public.pricing_catalog c, jsonb_array_elements(c.data->'rows') r
where c.id = ${q(id)} and coalesce(r->>'Part #', '') not in ('', '0') and ${seededRow(dt)}
on conflict (item_no, screen_id, row_label, price_col) do nothing;`,
  );
}
emit(`-- 8b. Pipe stacks: open and closed part numbers → Price`);
for (const [id, , dt] of screenCols.filter(([i]) => i.endsWith(":pipe_stacks")))
  emit(
    `insert into public.catalog_item_numbers (item_no, screen_id, row_label, price_col, dl_description)
select r->>k, c.id, r->>'Description', 'Price', r->>'Description'
from public.pricing_catalog c, jsonb_array_elements(c.data->'rows') r, unnest(array['Open Part #','Closed Part #']) k
where c.id = ${q(id)} and coalesce(r->>k, '') not in ('', '0') and ${seededRow(dt)}
on conflict (item_no, screen_id, row_label, price_col) do nothing;`,
  );
emit(`-- 8c. Duro-Tech tan and gray: TW → TB / TG at the same price (the sheet's note)`);
emit(
  `insert into public.catalog_item_numbers (item_no, screen_id, row_label, price_col, dl_description)
select left(r->>k, -2) || v.suffix, c.id, r->>'Description', v.col, r->>'Description' || ' (' || v.colour || ')'
from public.pricing_catalog c, jsonb_array_elements(c.data->'rows') r, unnest(array['Open Part #','Closed Part #']) k,
  (values ('TB', 'Tan Price', 'Tan'), ('TG', 'Gray Price', 'Gray')) v(suffix, col, colour)
where c.id = 'duro_last:pipe_stacks' and r->>k like '%TW' and r->>'Description' like 'Duro-Tech TPO %'
on conflict (item_no, screen_id, row_label, price_col) do nothing;`,
);
emit(
  `insert into public.catalog_item_numbers (item_no, screen_id, row_label, price_col, dl_description)
select left(r->>'Part #', -2) || v.suffix, c.id, r->>'Description', v.col, r->>'Description' || ' (' || v.colour || ')'
from public.pricing_catalog c, jsonb_array_elements(c.data->'rows') r,
  (values ('TB', 'Tan', 'Tan'), ('TG', 'Gray', 'Gray')) v(suffix, col, colour)
where c.id = 'duro_last:corners' and r->>'Part #' like '%TW' and r->>'Description' like 'Duro-Tech TPO %'
on conflict (item_no, screen_id, row_label, price_col) do nothing;`,
);
emit(
  `-- 8d. Firestone colour codes: W56TPO3… (white) → W56TPOT… (tan) / W56TPOG… (gray) on colour-priced rows`,
);
emit(
  `insert into public.catalog_item_numbers (item_no, screen_id, row_label, price_col, dl_description)
select v.pre || substr(r->>'Part #', 8), c.id, r->>'Description', v.col, r->>'Description' || ' (' || v.colour || ')'
from public.pricing_catalog c, jsonb_array_elements(c.data->'rows') r,
  (values ('W56TPOT', 'Tan', 'Tan'), ('W56TPOG', 'Gray', 'Gray')) v(pre, col, colour)
where c.id = 'non_dl_tpo:corners' and r->>'Part #' like 'W56TPO3%' and coalesce(r->>'Tan', '') <> ''
on conflict (item_no, screen_id, row_label, price_col) do nothing;`,
);
emit(
  `insert into public.catalog_item_numbers (item_no, screen_id, row_label, price_col, dl_description)
select v.pre || substr(r->>'Open Part #', 8), c.id, r->>'Description', v.col, r->>'Description' || ' (' || v.colour || ')'
from public.pricing_catalog c, jsonb_array_elements(c.data->'rows') r,
  (values ('W56TPOT', 'Tan Price', 'Tan'), ('W56TPOG', 'Gray Price', 'Gray')) v(pre, col, colour)
where c.id = 'non_dl_tpo:pipe_stacks' and r->>'Open Part #' like 'W56TPO3%'
on conflict (item_no, screen_id, row_label, price_col) do nothing;`,
);
emit(
  `-- 8e. Mappings without a Part # column (membrane rolls, pitch pans, custom applications, adhesives)`,
);
const listed = seedItemNumbers(EXISTING_COLUMNS).filter((m) =>
  [
    "duro_last:duro_last_membrane",
    "duro_last:exceptional_metals",
    "non_dl:preset_custom_applications",
    "duro_last:adhesives",
  ].includes(m.screen_id),
);
emit(
  `insert into public.catalog_item_numbers (item_no, screen_id, row_label, price_col, dl_description) values
  ${listed.map((m) => `(${q(m.item_no)}, ${q(m.screen_id)}, ${q(m.row_label)}, ${q(m.price_col)}, ${q(m.dl_description)})`).join(",\n  ")}
on conflict (item_no, screen_id, row_label, price_col) do nothing;`,
);
const mappings = seedItemNumbers(EXISTING_COLUMNS);

emit(
  `\n-- Seed totals: ${FAMILY_SCREENS.length} screens, ${FAMILY_SCREENS.reduce((n, s) => n + s.rows.length, 0)} family rows, ${DURO_LAST_ADDITIONS.reduce((n, a) => n + a.rows.length, 0)} Duro-Tech rows, ${ADHESIVE_PRODUCTS.length} adhesives, ${PITCH_PAN_ROWS.length} pitch pans, ${CUSTOM_APPLICATION_ROWS.length} custom applications, ${mappings.length} item numbers.`,
);

process.stdout.write(out.join("\n") + "\n");
